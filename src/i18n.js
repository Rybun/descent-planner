/**
 * Devuelve la función de traducción `t(key, vars?)` reactiva al idioma actual.
 * Uso: const t = useT();  →  t('shop.buy')  →  "Comprar" / "Buy" / ...
 */
export function useT() {
  const lang = useStore(s => s.lang);
  return useCallback((key, vars) => {
    const dict = T[lang] ?? T.es;
    const str  = dict[key] ?? T.es[key] ?? key;
    if (!vars) return str;
    return str.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '');
  }, [lang]);
}

/**
 * Devuelve el idioma actual (string: 'es' | 'en' | 'fr' | 'it' | 'pt').
 */
export function useLang() {
  return useStore(s => s.lang);
}

